// Generates worker/content.generated.js from server/words.js so the Worker can seed D1
// with a handful of cheap json_each() statements instead of ~1000 bound inserts.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { TOPICS } from '../server/words.js';

const CHUNK = 150;
const topics = TOPICS.map((t) => ({ slug: t.slug, name: t.name, emoji: t.emoji, color: t.color, level: t.level ?? null }));
const rows = TOPICS.flatMap((t) => t.words.map((w) => ({
  s: t.slug, w: w.word, vi: w.vi, ph: w.ph ?? null, d: w.def ?? null, e: w.ex ?? null,
  em: w.emoji ?? null, q: w.q ?? w.word, p: w.pos ?? null, xv: w.exVi ?? null,
})));
const chunks = [];
for (let i = 0; i < rows.length; i += CHUNK) chunks.push(JSON.stringify(rows.slice(i, i + CHUNK)));

const topicsJson = JSON.stringify(topics);
const version = createHash('sha1').update(topicsJson).update(chunks.join('')).digest('hex').slice(0, 12);

const out = `// AUTO-GENERATED by scripts/build-content.mjs from server/words.js. Do not edit.
export const CONTENT_VERSION = ${JSON.stringify(version)};
export const TOPICS_JSON = ${JSON.stringify(topicsJson)};
export const WORD_CHUNKS = ${JSON.stringify(chunks)};
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'worker', 'content.generated.js');
writeFileSync(target, out);
console.log(`content: ${topics.length} topics, ${rows.length} words, ${chunks.length} chunks, version ${version}`);
